"""fig_sft.py LOG OUT.typ [WINDOW]: the SFT figure (sec/fig-sft-loss.typ) from a TorchTitan log, drawn with cetz.

Each step's training loss (grey), its WINDOW-step trailing mean (black; default 25) and the held-out loss TorchTitan's validator logs
("validate step: N loss: ..."; circles). Defines `fig-sft-loss`; the caption is the one in sec/training.typ's
figure call. Adapted from ~/tt-work/train35/loss_figure.py, which drew the published MetaMathQA run.
"""
import re
import sys

log, out = sys.argv[1], sys.argv[2]
window = int(sys.argv[3]) if len(sys.argv) > 3 else 25
text = re.sub(r"\x1b\[[0-9;]*m", "", open(log, errors="ignore").read())
train, held = {}, {}
for m in re.finditer(r"validate step:\s*(\d+)\s+loss:\s*([\d.]+)", text):
    held.setdefault(int(m.group(1)), float(m.group(2)))
for m in re.finditer(r"(?<!validate )step:\s*(\d+)\s+loss:\s*([\d.]+)\s+grad_norm", text):
    train.setdefault(int(m.group(1)), float(m.group(2)))
xs = sorted(train)
ys = [train[x] for x in xs]
avg = [sum(ys[max(0, i - window + 1): i + 1]) / len(ys[max(0, i - window + 1): i + 1]) for i in range(len(ys))]
n = xs[-1]
top = max(0.1, round(max(ys + list(held.values())) * 10 + 0.5) / 10)
W, H = 11.0, 5.0  # cm


def px(x):
    return f"{(x - 1) / max(1, n - 1) * W:.3f}"


def py(y):
    return f"{min(y, top) / top * H:.3f}"


step = 0.1 if top <= 0.6 else 0.2
yticks = [round(i * step, 1) for i in range(int(round(top / step)) + 1)]
xticks = [1] + list(range(50, n + 1, 50))
body = [
    '#import "@preview/cetz:0.5.3"',
    "",
    f"// Generated by scripts/fig_sft.py from {log}.",
    "#let fig-sft-loss = cetz.canvas(length: 1cm, {",
    "  import cetz.draw: *",
    "  set-style(stroke: (thickness: 0.5pt))",
    f"  line((0, 0), ({W}, 0))",
    f"  line((0, 0), (0, {H}))",
]
for t in xticks:
    body += [f"  line(({px(t)}, 0), ({px(t)}, -0.12))", f"  content(({px(t)}, -0.45), text(size: 8pt)[{t}])"]
for t in yticks:
    body += [f"  line((0, {py(t)}), (-0.12, {py(t)}))", f"  content((-0.5, {py(t)}), text(size: 8pt)[{t:.1f}])"]
body.append(f'  content(({W / 2:.2f}, -1.0), text(size: 8.5pt, style: "italic")[Step])')
body.append(f'  content((-1.25, {H / 2:.2f}), angle: 90deg, text(size: 8.5pt, style: "italic")[Loss])')
pts = ", ".join(f"({px(x)}, {py(y)})" for x, y in zip(xs, ys))
body.append(f"  line({pts}, stroke: (paint: luma(170), thickness: 0.4pt))")
pts = ", ".join(f"({px(x)}, {py(y)})" for x, y in zip(xs, avg))
body.append(f"  line({pts}, stroke: (paint: black, thickness: 0.9pt))")
for x, y in sorted(held.items()):
    body.append(f"  circle(({px(x)}, {py(y)}), radius: 0.07, fill: white, stroke: (paint: black, thickness: 0.6pt))")
body += ["})", ""]
open(out, "w").write("\n".join(body))
first10 = sum(ys[:10]) / min(10, len(ys))
last10 = sum(ys[-10:]) / min(10, len(ys))
print(f"{len(xs)} steps; first {ys[0]:.4f}; mean of first 10 {first10:.4f}; mean of last 10 {last10:.4f}; "
      f"held-out {sorted(held.items())}")
