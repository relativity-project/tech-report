"""fig_rl.py OUT.typ: the RL figure (sec/fig-rl-learning.typ) from the run logs, drawn with cetz like the SFT figure.

Three 90-step runs with different seeds: the published run (long3, seed 1234 / 42, libtt 0.2.1) and two second-pass
runs (seeds 1235 / 43 and 1236 / 44, libtt 0.2.2 release 2c68912a). Left: training reward (the mean over each step's
128 answers) as trailing 15-step means, one colour per run. Right: test accuracy on all 1,319 GSM8K questions (greedy,
1,024 tokens) after steps 30, 60 and 90 for each run (coloured dots and lines) and their mean (black, open circles). Step 0: long3's fresh-server
check (0.2.1) for long3, and the second pass's one step-0 evaluation (f6_s2) for both new runs, which start from the
same policy.

Inputs (this machine's paths, recorded in the output's header):
  published run      ~/tt-work/miles/runs/long3/train.log and ~/tt-work/rl-report-20261117/evaluation-summary.json
  new seeds          ~/tt-work/techreport/exp/rl/runs/f6_s{2,3}/train.log
"""
import json
import os
import re
import sys

HOME = os.path.expanduser("~")
RUNS = f"{HOME}/tt-work/techreport/exp/rl/runs"
LONG3 = f"{HOME}/tt-work/miles/runs/long3/train.log"
ENDPOINTS = f"{HOME}/tt-work/rl-report-20261117/evaluation-summary.json"
SEEDS = [LONG3] + [f"{RUNS}/f6_s{i}/train.log" for i in (2, 3)]
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def parse(path):
    if not os.path.exists(path):
        return {}, {}
    text = ANSI.sub("", open(path, errors="replace").read())
    rewards = {}
    for m in re.finditer(r"rollout (\d+): \{.*?'rollout/raw_reward_filtered': ([0-9.]+)", text):
        rewards.setdefault(int(m[1]) + 1, float(m[2]))  # rollout r is step r + 1
    evals = {}
    first_rollout = text.find("rollout 0: {")
    for m in re.finditer(r"eval (\d+): \{[^}]*?'eval/gsm8k': ([0-9.]+)", text):
        # Miles logs an evaluation with the rollout id after which it ran; the one before training is step 0.
        step = 0 if 0 <= m.start() < first_rollout or first_rollout < 0 and int(m[1]) == 0 else int(m[1]) + 1
        evals.setdefault(step, float(m[2]))
    return rewards, evals


seeds = [parse(p) for p in SEEDS]
seeds[0][1].setdefault(0, json.load(open(ENDPOINTS))["base1024"]["accuracy"])  # long3's fresh-server step 0
if 0 in seeds[1][1]:  # the second pass's one step-0 evaluation, for both new runs
    seeds[2][1].setdefault(0, seeds[1][1][0])

W, H, GAP = 6.2, 4.4, 2.0
RX = W + GAP


def lx(s):
    return s / 90 * W


def ly(r):
    return (r - 0.3) / 0.7 * H  # reward 0.3 .. 1.0


def ax(s):
    return RX + s / 90 * W


def ay(a):
    return (a - 0.50) / 0.30 * H  # accuracy 50% .. 80%


def pts(p):
    return ", ".join(f"({x:.3f}, {y:.3f})" for x, y in p)


def trailing(rew, k=15):
    ss = sorted(rew)
    return [(s, sum(rew[t] for t in ss if s - k < t <= s) / len([t for t in ss if s - k < t <= s])) for s in ss]


out = [
    '#import "@preview/cetz:0.5.3"',
    "",
    f"// Generated by scripts/fig_rl.py from {', '.join(SEEDS)},",
    f"// and {ENDPOINTS}.",
    "#let rl-learning-image = cetz.canvas(length: 1cm, {",
    "  import cetz.draw: *",
    "  set-style(stroke: (thickness: 0.5pt))",
]
for x0 in (0, RX):
    out += [f"  line(({x0}, 0), ({x0 + W}, 0))", f"  line(({x0}, 0), ({x0}, {H}))"]
    for s in (0, 30, 60, 90):
        x = x0 + s / 90 * W
        out += [f"  line(({x:.3f}, 0), ({x:.3f}, -0.12))", f"  content(({x:.3f}, -0.42), text(size: 8pt)[{s}])"]
    out.append(f"  content(({x0 + W / 2:.2f}, -0.95), text(size: 8.5pt, style: \"italic\")[Step])")
for r in (0.4, 0.6, 0.8, 1.0):
    out += [f"  line((0, {ly(r):.3f}), (-0.12, {ly(r):.3f}))", f"  content((-0.45, {ly(r):.3f}), text(size: 8pt)[{r:.1f}])"]
out.append(f"  content((-1.1, {H / 2:.2f}), angle: 90deg, text(size: 8.5pt, style: \"italic\")[Training reward])")
for a in (0.5, 0.6, 0.7, 0.8):
    y = ay(a)
    out += [f"  line(({RX}, {y:.3f}), ({RX - 0.12}, {y:.3f}))", f"  content(({RX - 0.5}, {y:.3f}), text(size: 8pt)[{a * 100:.0f}%])"]
out.append(f"  content(({RX - 1.15}, {H / 2:.2f}), angle: 90deg, text(size: 8.5pt, style: \"italic\")[Test accuracy])")

colors = ["rgb(\"#1f5fa8\")", "rgb(\"#b5462a\")", "rgb(\"#2a7a3b\")"]

# Left panel: rewards.
for (rew, _), c in zip(seeds, colors):
    if rew:
        out.append(f"  line({pts((lx(s), ly(v)) for s, v in trailing(rew))}, stroke: (paint: {c}, thickness: 0.7pt))")

# Right panel: test accuracy.
for (_, e), c in zip(seeds, colors):
    if e:
        out.append(f"  line({pts((ax(s), ay(a)) for s, a in sorted(e.items()))}, stroke: (paint: {c}, thickness: 0.5pt))")
        for s, a in sorted(e.items()):
            out.append(f"  circle(({ax(s):.3f}, {ay(a):.3f}), radius: 0.045, fill: {c}, stroke: none)")
common = sorted(set.intersection(*(set(e) for _, e in seeds))) if all(e for _, e in seeds) else []
mean = [(s, sum(e[s] for _, e in seeds) / len(seeds)) for s in common]
if mean:
    out.append(f"  line({pts((ax(s), ay(a)) for s, a in mean)}, stroke: (paint: black, thickness: 0.9pt))")
    for s, a in mean:
        out.append(f"  circle(({ax(s):.3f}, {ay(a):.3f}), radius: 0.07, fill: white, stroke: (paint: black, thickness: 0.6pt))")
out += ["})", ""]
open(sys.argv[1], "w").write("\n".join(out))
for p, (r, e) in zip(SEEDS, seeds):
    print(p, "steps", len(r), "evals", {s: round(a * 100, 2) for s, a in sorted(e.items())})
print("mean", {s: round(a * 100, 2) for s, a in mean})
