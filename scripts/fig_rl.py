"""fig_rl.py OUT.typ: the RL figure (sec/fig-rl-learning.typ) from the run logs, drawn with cetz like the SFT figure.

Left: training reward per step (the mean over the step's 128 answers) of the published run (grey; its trailing
15-step mean in black) and of the libtt 0.2.2 seeds (thin coloured lines). Right: test accuracy on all 1,319 GSM8K
questions (greedy, 1,024 tokens): the published run's in-run evaluations (circles) and fresh-server checks
(squares), the 0.2.2 seeds' evaluations (dots, with the min-max band over the published run and the seeds for
steps 0-30), and the zero-learning-rate control (dashed).

Inputs (this machine's paths, recorded in the output's header):
  published run      ~/tt-work/miles/runs/long3/train.log and ~/tt-work/rl-report-20261117/evaluation-summary.json
  seeds (0.2.2)      ~/tt-work/techreport/exp/rl/runs/r1_s*/train.log
  zero-LR control    ~/tt-work/techreport/exp/rl/runs/r2_lr0/train.log
"""
import glob
import json
import os
import re
import sys

HOME = os.path.expanduser("~")
LONG3 = f"{HOME}/tt-work/miles/runs/long3/train.log"
ENDPOINTS = f"{HOME}/tt-work/rl-report-20261117/evaluation-summary.json"
SEEDS = sorted(glob.glob(f"{HOME}/tt-work/techreport/exp/rl/runs/r1_s*/train.log"))
R2 = f"{HOME}/tt-work/techreport/exp/rl/runs/r2_lr0/train.log"
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def parse(path):
    text = ANSI.sub("", open(path, errors="replace").read())
    rewards = {}
    for m in re.finditer(r"rollout (\d+): \{.*?'rollout/raw_reward_filtered': ([0-9.]+)", text):
        rewards.setdefault(int(m[1]) + 1, float(m[2]))  # rollout r is step r + 1
    evals = {}
    first_rollout = text.find("rollout 0: {")
    for m in re.finditer(r"eval (\d+): \{[^}]*?'eval/gsm8k': ([0-9.]+)", text):
        # Miles logs an evaluation with the rollout id after which it ran; one before training is step 0.
        step = 0 if 0 <= m.start() < first_rollout or first_rollout < 0 and int(m[1]) == 0 else int(m[1]) + 1
        evals.setdefault(step, float(m[2]))
    return rewards, evals


pub_r, pub_e = parse(LONG3)
ends = json.load(open(ENDPOINTS))
fresh = {0: ends["base1024"]["accuracy"], 90: ends["step90"]["accuracy"]}
seeds = [parse(p) for p in SEEDS]
r2_r, r2_e = parse(R2) if os.path.exists(R2) else ({}, {})

W, H, GAP = 6.2, 4.4, 2.0
RX = W + GAP


def lx(s):
    return s / 90 * W


def ly(r):
    return (r - 0.3) / 0.7 * H  # reward 0.3 .. 1.0


def ax(s):
    return RX + s / 90 * W


def ay(a):
    return (a - 0.50) / 0.30 * H  # accuracy 50% .. 80%


def pts(p):
    return ", ".join(f"({x:.3f}, {y:.3f})" for x, y in p)


out = [
    '#import "@preview/cetz:0.5.3"',
    "",
    f"// Generated by scripts/fig_rl.py from {LONG3}, {ENDPOINTS},",
    f"// {', '.join(SEEDS) or 'no seed runs'} and {R2}.",
    "#let rl-learning-image = cetz.canvas(length: 1cm, {",
    "  import cetz.draw: *",
    "  set-style(stroke: (thickness: 0.5pt))",
]
for x0 in (0, RX):
    out += [f"  line(({x0}, 0), ({x0 + W}, 0))", f"  line(({x0}, 0), ({x0}, {H}))"]
    for s in (0, 30, 60, 90):
        x = x0 + s / 90 * W
        out += [f"  line(({x:.3f}, 0), ({x:.3f}, -0.12))", f"  content(({x:.3f}, -0.42), text(size: 8pt)[{s}])"]
    out.append(f"  content(({x0 + W / 2:.2f}, -0.95), text(size: 8.5pt, style: \"italic\")[Step])")
for r in (0.4, 0.6, 0.8, 1.0):
    out += [f"  line((0, {ly(r):.3f}), (-0.12, {ly(r):.3f}))", f"  content((-0.45, {ly(r):.3f}), text(size: 8pt)[{r:.1f}])"]
out.append(f"  content((-1.1, {H / 2:.2f}), angle: 90deg, text(size: 8.5pt, style: \"italic\")[Training reward])")
for a in (0.5, 0.6, 0.7, 0.8):
    y = ay(a)
    out += [f"  line(({RX}, {y:.3f}), ({RX - 0.12}, {y:.3f}))", f"  content(({RX - 0.5}, {y:.3f}), text(size: 8pt)[{a * 100:.0f}%])"]
out.append(f"  content(({RX - 1.15}, {H / 2:.2f}), angle: 90deg, text(size: 8.5pt, style: \"italic\")[Test accuracy])")

# Left panel: rewards.
steps = sorted(pub_r)
out.append(f"  line({pts((lx(s), ly(pub_r[s])) for s in steps)}, stroke: (paint: luma(175), thickness: 0.4pt))")
trail = [(s, sum(pub_r[t] for t in steps if s - 15 < t <= s) / len([t for t in steps if s - 15 < t <= s])) for s in steps]
out.append(f"  line({pts((lx(s), ly(v)) for s, v in trail)}, stroke: (paint: black, thickness: 0.9pt))")
colors = ["rgb(\"#1f5fa8\")", "rgb(\"#b5462a\")", "rgb(\"#2a7a3b\")"]
def trailing(rew, k=15):
    ss = sorted(rew)
    return [(s, sum(rew[t] for t in ss if s - k < t <= s) / len([t for t in ss if s - k < t <= s])) for s in ss]


for (rew, _), c in zip(seeds, colors):
    out.append(f"  line({pts((lx(s), ly(v)) for s, v in trailing(rew))}, stroke: (paint: {c}, thickness: 0.7pt))")
if r2_r:
    out.append(f"  line({pts((lx(s), ly(v)) for s, v in trailing(r2_r))}, stroke: (paint: black, thickness: 0.6pt, dash: \"dashed\"))")

# Right panel: test accuracy.
early = sorted({0} | {s for _, e in seeds for s in e if s <= 30} | {s for s in pub_e if s <= 30})
band = []
for s in early:
    vals = [e[s] for _, e in seeds if s in e] + ([pub_e[s]] if s in pub_e else []) + ([fresh[0]] if s == 0 else [])
    if s == 0 and r2_e.get(0) is not None:
        vals.append(r2_e[0])
    if len(vals) >= 2:
        band.append((s, min(vals), max(vals)))
if len(band) >= 2:
    poly = [(ax(s), ay(lo)) for s, lo, _ in band] + [(ax(s), ay(hi)) for s, _, hi in reversed(band)]
    out.append(f"  line({pts(poly)}, close: true, fill: luma(225), stroke: none)")
pub_pts = sorted(pub_e.items())
if pub_pts:
    out.append(f"  line({pts((ax(s), ay(a)) for s, a in [(0, fresh[0])] + pub_pts)}, stroke: (paint: black, thickness: 0.8pt))")
for s, a in pub_pts:
    out.append(f"  circle(({ax(s):.3f}, {ay(a):.3f}), radius: 0.07, fill: white, stroke: (paint: black, thickness: 0.6pt))")
for s, a in fresh.items():
    out.append(f"  rect(({ax(s) - 0.07:.3f}, {ay(a) - 0.07:.3f}), ({ax(s) + 0.07:.3f}, {ay(a) + 0.07:.3f}), fill: black)")
for (_, e), c in zip(seeds, colors):
    for s, a in sorted(e.items()):
        out.append(f"  circle(({ax(s):.3f}, {ay(a):.3f}), radius: 0.05, fill: {c}, stroke: none)")
if r2_e:
    ss = sorted(r2_e)
    out.append(f"  line({pts((ax(s), ay(r2_e[s])) for s in ss)}, stroke: (paint: black, thickness: 0.6pt, dash: \"dashed\"))")
out += ["})", ""]
open(sys.argv[1], "w").write("\n".join(out))
print("published evals", pub_e, "fresh", fresh)
print("seeds", [e for _, e in seeds], "r2", r2_e)
print("band", band)
